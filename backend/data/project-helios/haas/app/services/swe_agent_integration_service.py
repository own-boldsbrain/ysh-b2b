_INITIALIZED = False


async def _execute_code_generation(payload: Dict[str, Any]) -> Dict[str, Any]:
    """Execute code generation using SWE-agent."""
    task_description = payload.get("task_description", "")
    context = payload.get("context", {})

    if not task_description:
        return {"status": "error", "reason": "no_task_description"}

    try:
        # Use TaskOrchestrator to decompose and execute code generation task
        task_id = await TASK_ORCHESTRATOR.execute_task(
            task_description, context=context, max_parallel=2
        )

        return {
            "status": "initiated",
            "task_id": task_id,
            "message": "Code generation task initiated via SWE-agent"
        }

    except Exception as e:
        logger.error(f"Error in code generation: {e}")
        return {"status": "error", "reason": str(e)}


async def _execute_script_validation(payload: Dict[str, Any]) -> Dict[str, Any]:
    """Validate generated script using SWE-agent."""
    script_code = payload.get("script_code", "")
    test_cases = payload.get("test_cases", [])

    if not script_code:
        return {"status": "error", "reason": "no_script_code"}

    try:
        # Create temporary file for script validation
        with tempfile.NamedTemporaryFile(mode='w', suffix='.py', delete=False) as f:
            f.write(script_code)
            temp_script_path = f.name

        # Run basic syntax check
        result = subprocess.run(
            [settings.PYTHON_EXECUTABLE or 'python', '-m', 'py_compile', temp_script_path],
            capture_output=True,
            text=True,
            timeout=30
        )

        # Clean up
        os.unlink(temp_script_path)

        if result.returncode == 0:
            return {
                "status": "valid",
                "syntax_check": "passed",
                "message": "Script syntax is valid"
            }
        else:
            return {
                "status": "invalid",
                "syntax_check": "failed",
                "errors": result.stderr.split('\n') if result.stderr else []
            }

    except subprocess.TimeoutExpired:
        return {"status": "error", "reason": "validation_timeout"}
    except Exception as e:
        logger.error(f"Error in script validation: {e}")
        return {"status": "error", "reason": str(e)}


async def _execute_data_extraction_script(payload: Dict[str, Any]) -> Dict[str, Any]:
    """Execute data extraction script generated by SWE-agent."""
    script_path = payload.get("script_path", "")
    parameters = payload.get("parameters", {})

    if not script_path or not Path(script_path).exists():
        return {"status": "error", "reason": "script_not_found"}

    try:
        # Execute script with parameters
        env = os.environ.copy()
        env.update({f"PARAM_{k.upper()}": str(v) for k, v in parameters.items()})

        result = subprocess.run(
            [settings.PYTHON_EXECUTABLE or 'python', script_path],
            env=env,
            capture_output=True,
            text=True,
            timeout=300  # 5 minutes timeout
        )

        return {
            "status": "completed" if result.returncode == 0 else "failed",
            "return_code": result.returncode,
            "stdout": result.stdout,
            "stderr": result.stderr,
            "execution_time": "completed"
        }

    except subprocess.TimeoutExpired:
        return {"status": "error", "reason": "execution_timeout"}
    except Exception as e:
        logger.error(f"Error executing data extraction script: {e}")
        return {"status": "error", "reason": str(e)}


