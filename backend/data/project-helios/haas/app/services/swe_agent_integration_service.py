class SWEAgentIntegrationService:
    """Service class for SWE-agent integration operations."""

    async def list_supported_code_tasks(self) -> List[str]:
        """List supported code generation tasks."""
        return [
            "data_extraction_script",
            "api_integration_script",
            "data_transformation_script",
            "validation_script",
            "reporting_script"
        ]

    async def generate_code(
        self,
        task_type: str,
        specifications: Dict[str, Any]
    ) -> str:
        """Generate code using SWE-agent."""
        task_description = f"Generate {task_type} with specifications: {json.dumps(specifications)}"

        context = {
            "task_type": task_type,
            "specifications": specifications,
            "script_type": task_type.replace("_script", ""),
        }

        task_id = await run_code_generation_task(
            task_description,
            context=context
        )

        return task_id

    async def validate_script(self, script_code: str) -> Dict[str, Any]:
        """Validate a generated script."""
        payload = {
            "script_code": script_code,
            "test_cases": []  # Could be expanded
        }

        result = await _execute_script_validation(payload)
        return result

    async def execute_script(
        self,
        script_path: str,
        parameters: Optional[Dict[str, Any]] = None
    ) -> Dict[str, Any]:
        """Execute a data extraction script."""
        payload = {
            "script_path": script_path,
            "parameters": parameters or {}
        }

        result = await _execute_data_extraction_script(payload)
        return result

    async def get_task_status(self, task_id: str) -> Dict[str, Any]:
        """Get task status from TaskOrchestrator."""
        try:
            progress_report = await TASK_ORCHESTRATOR.monitor_progress(task_id)
            return {
                "task_id": task_id,
                "status": progress_report.status.value,
                "progress": progress_report.progress,
                "current_subtasks": [
                    {
                        "id": st["id"],
                        "description": st["description"],
                        "status": st.get("status", "unknown")
                    }
                    for st in progress_report.current_subtasks
                ],
                "completed_subtasks": [
                    {
                        "id": st["id"],
                        "description": st["description"],
                        "result": st.get("result", "")
                    }
                    for st in progress_report.completed_subtasks
                ],
                "failed_subtasks": [
                    {
                        "id": st["id"],
                        "description": st["description"],
                        "error": st.get("error", "")
                    }
                    for st in progress_report.failed_subtasks
                ],
            }
        except Exception as e:
            return {
                "task_id": task_id,
                "status": "error",
                "error": str(e)
            }